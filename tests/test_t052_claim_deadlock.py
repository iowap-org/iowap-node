class StageClient(FakeClient):
    """FakeClient that hands out ONE staged payload on the first claim."""

    def __init__(self, stage: dict) -> None:
        super().__init__()
        self.stage = stage
        self._executed: list[tuple[dict, dict]] = []

    def claim(self, capability: str):
        with self._mutex:
            self.claim_attempts.append(capability)
            if self.claim_attempts.count(capability) == 1:
                return self.stage
        return None


def _daemon(client) -> node_daemon.SseDaemon:
    d = node_daemon.SseDaemon.__new__(node_daemon.SseDaemon)
    d.client = client
    d.cfg = {"heartbeat_interval": 30, "backfill_interval": 60, "max_retries": 2}
    d.server_probe = {"ok": True, "error": ""}
    d.tasks_completed = 0
    d.tasks_failed = 0
    d._failed_tasks = {}
    d._in_flight = {}
    d._in_flight_points = 0
    from datetime import UTC, datetime

    d._started_at = datetime.now(UTC)
    d._lock = threading.Lock()
    d._stop_event = threading.Event()
    d._backfill_thread = None
    d._backfill_armed = threading.Event()
    d._claim_wake = threading.Event()
    d._claim_hint = None
    return d


def _prepare_full_chain(t052_env, monkeypatch) -> StageClient:
    """legacy stale entry → load heals → poll refreshes → registry claimable."""
    _write_active(node_config.ACTIVE_PATH, LEGACY_NODE_YAML)
    _seed_store({"name": "systeminfo", "type": "process", "command": "sysinfo.exe"})
    _stub_manifest(monkeypatch, MANIFEST_SYSINFO_DOWN)
    bridge.get_manager().poll_once()
    # the refreshed registry copy of the same name sits NEXT TO the file
    merged = node_config.load_active_profile()
    copies = [c for c in merged if c["name"] == "host.systeminfo"]
    assert len(copies) == 2
    assert [c["claimable"] for c in copies] == [False, True]
    client = StageClient(
        {"task_id": "task_07J-j0UH4sGPKwJx", "stage_id": "s1", "payload": {"mode": "full"}}
    )
    return client


def test_claimed_after_fix(t052_env, monkeypatch):
    """The whole T-052 chain on the owner-pinned path: task_created for
    host.systeminfo → the claim-eligible registry copy wins
    (_find_capability no longer starves on the non-claimable baked
    copy) → claim dispatched → stage routes to the bridge exec with the
    forwarded bridge pair → completed."""
    client = _prepare_full_chain(t052_env, monkeypatch)
    d = _daemon(client)

    fwd_calls: list[tuple[dict, dict]] = []

    def fake_exec(client_, cap, stage):
        fwd_calls.append((cap, stage))
        return {"status": "completed", "result": {"mode": stage["payload"]["mode"]}}

    monkeypatch.setattr(node_daemon.bridge, "execute_bridge_task", fake_exec)

    d._on_event(
        {
            "type": "task_created",
            "data": {
                "payload": {
                    "task_id": "task_07J-j0UH4sGPKwJx",
                    "capabilities": ["host.systeminfo"],
                }
            },
        }
    )
    assert client.claim_attempts == ["host.systeminfo"]
    assert len(fwd_calls) == 1
    cap, stage = fwd_calls[0]
    assert cap["bridge_name"] == "systeminfo"  # forwarded bridge pair
    assert cap["claimable"] is True  # THE REGISTRY COPY routed the claim
    assert stage["task_id"] == "task_07J-j0UH4sGPKwJx"
    assert client._completed == [("task_07J-j0UH4sGPKwJx", "s1")]


