"""T-052: claim deadlock — a stale baked bridge entry collides with its own cap.

Field evidence (Ronny-Log bridgecapfehler.txt, UXNWPARK, 27.11 23:53–
28.11 00:56): every manifest poll logged

    bridge manifest reports systeminfo health=down — publishing per allowlist
    bridge cap systeminfo skipped — collision with existing capability 'host.systeminfo'

and the owner-pinned tasks (task_07J-j0UH4sGPKwJx / task_4rWZnqwoe5xWE5CT)
stayed pending forever — no claim despite online+available (SSE +
backfill green, /agents/create + advisory + slots fine; the deadlock was
capability resolution).

Root-cause chain (anchored):

1. The active node.yaml carried a pre-schema baked bridge entry —
   ``host.systeminfo``, prefixed name, WITHOUT the ``bridge``/
   ``bridge_name`` router fields (baked in the T-045 migration window).
2. The recompose counted it as 0 bridge entries (classification by the
   router pair); ``load_active_profile_unmerged()`` served it as a
   local capability → the namespace rule made every manifest poll skip
   its own cap → the runtime registry stayed empty for the name → no
   claim eligibility → task pending, forever (ping-pong between the
   file and the registry).

Fixes proven here as ONE chain:

* legacy baked entries are recognized and healed — ``bridge: True`` +
  ``bridge_name: <bare>`` — in-memory at load (log-once, "legacy baked
  bridge entries normalized (N)") and regenerated by the next recompose
  write (routing-complete baked form);
* the manifest poll refreshes a same-cap baked entry IN PLACE ("bridge
  cap %s refreshed from manifest") instead of skipping; a true local
  capability (claimable + handler) keeps colliding — namespace rule
  unchanged;
* the claim sweep sees the CLAIMABLE registry copy (claim-eligibility
  consolidation) → claim dispatched, stage forwards to the bridge
  (exec-able).
"""

