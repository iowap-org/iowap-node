def _seed_store(*entries: dict) -> None:
    """Write providers.yaml directly — NO store-mutation recompose, the
    tests control the file state explicitly (create_provider would bake)."""
    ws = Path(os.environ["IOWAP_WORKSPACE_DIR"]) / "bridge"
