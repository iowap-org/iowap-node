def test_stale_registry_no_claim(t052_env, monkeypatch):
    """Without a populated registry the claim stays impossible: with the
    manifest poll dead (fetch failing), only the healed baked copy
    (claimable=False) exists — the targeted sweep refuses, exactly the
    field state that kept the owner-pinned tasks pending."""
