def test_legacy_normalize(t052_env, monkeypatch, caplog):
    """The stale in-memory view: the legacy entry heals at load — router
    pair added, prefixed name kept — while the FILE stays untouched and
    a true local host.* capability (handler semantics) does NOT heal."""
    _write_active(
        node_config.ACTIVE_PATH,
        LEGACY_NODE_YAML
        + "- name: host.local.tool\n"
        + "  version: 1.0.0\n"
        + "  claimable: true\n"
        + "  handler: /bin/true\n",
    )
    with caplog.at_level(logging.INFO):
        base = node_config.load_active_profile_unmerged()

    by_name = {c["name"]: c for c in base}
    healed = by_name["host.systeminfo"]
    assert healed["bridge"] is True
    assert healed["bridge_name"] == "systeminfo"  # the de-prefixed name
    assert healed["name"] == "host.systeminfo"  # wire identity unchanged
    assert healed["claimable"] is False  # never executed locally

    # a true local keeps its identity — no heal, no router fields
    local = by_name["host.local.tool"]
    assert "bridge" not in local and "bridge_name" not in local

    # the heal is IN-MEMORY: the file still carries the stale form
    doc = yaml.safe_load(node_config.ACTIVE_PATH.read_text())
    stale = [c for c in doc["capabilities"] if c["name"] == "host.systeminfo"][0]
    assert "bridge" not in stale and "bridge_name" not in stale

    # log-once: the exact migration line, exactly one per process
    lines = [
        r for r in caplog.records
        if "legacy baked bridge entries normalized (1)" in r.message
    ]
    assert len(lines) == 1

    # log-once: further loads (fresh cache) stay silent
    node_config.invalidate_active_cache()
    with caplog.at_level(logging.INFO):
        node_config.load_active_profile_unmerged()
    assert [
        r for r in caplog.records
        if "legacy baked bridge entries normalized" in r.message
    ] == [lines[0]]  # the first record, no second one


