def test_update_in_place(t052_env, monkeypatch, caplog):
    """A MODERN baked entry (router pair present) is the SAME cap — the
    poll updates the runtime registry entry in place ('refreshed from
    manifest', current manifest fields ride) instead of skipping."""
    _write_active(
        node_config.ACTIVE_PATH,
        "bridge:\n"
        "  url: http://host.docker.internal:7780\n"
        "  token: bridging\n"
        "  allowlist: [systeminfo]\n"
        "capabilities:\n"
        "- name: host.systeminfo\n"
        "  version: 1.0.0\n"
        "  claimable: false\n"
        "  bridge: true\n"
        "  bridge_name: systeminfo\n",
    )
    _stub_manifest(
        monkeypatch,
        {
            "version": 1,
            "capabilities": [
                {
                    "name": "systeminfo",
                    "health": "ok",
                    "summary": "Host system information",
                    "version": "1.2.3",
                    "max_parallel": 2,
                    "cost": 3,
                }
            ],
        },
    )
    with caplog.at_level(logging.INFO, logger="bridge"):
        bridge.get_manager().poll_once()

    published = bridge.get_manager().published
    assert list(published) == ["host.systeminfo"]
    cap = published["host.systeminfo"]
    assert cap["bridge"] is True and cap["bridge_name"] == "systeminfo"
    assert cap["claimable"] is True  # the claim-eligible registry copy
    assert cap["version"] == "1.2.3"  # fields refreshed from the manifest
    assert cap["max_parallel"] == 2 and cap["cost"] == 3
    messages = [r.message for r in caplog.records]
    assert any("refreshed from manifest" in m for m in messages)
    assert not any("collision" in m for m in messages)


